public class Arithmetic_operations {
    public static void main(String[] args) {
        int a = 25;
        int b = 75;

        int sum = a + b;
        int subs = b - a;
        int mul = a * b;
        int div = b / a;

        System.out.println("Sum is:-" + sum);
        System.out.println("subs is:-" + subs);
        System.out.println("mul is:-" + mul);
        System.out.println("div is:-" + div);
    }
}
